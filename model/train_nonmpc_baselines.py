"""Policy-conditional 1h-ahead synthetic failure screening & safe-MILP imitation.

No RL/MPC; no patient or field risk estimates. Source must be generated by
``generate_nonmpc_training.py`` and split by independent accident FAMILY.
Stress OOD is NEVER mixed into train/test; if classes absent, say so.
"""
from __future__ import annotations
import argparse,json,sys
from pathlib import Path
sys.path.insert(0,str(Path(__file__).resolve().parent/"src"))
import numpy as np,pandas as pd
from joblib import dump
from sklearn.ensemble import RandomForestClassifier,RandomForestRegressor
from sklearn.metrics import (confusion_matrix,precision_score,recall_score,average_precision_score,
                             roc_auc_score,mean_absolute_error)
from sklearn.model_selection import train_test_split,GroupShuffleSplit
from hospital_ies.training_schema import build_features,FEATURES,ACTIONS


def _groups_split(data:pd.DataFrame,target:str,seed:int):
    groups=data.groupby('episode_family')[target].max()
    if len(groups)<6:raise ValueError('Need at least 6 independent accident families')
    strat=groups if groups.nunique()==2 and groups.value_counts().min()>=2 else None
    ids_tr,ids_te=train_test_split(groups.index.to_numpy(),test_size=0.3,random_state=seed,
                                   stratify=None if strat is None else strat.to_numpy())
    return data.episode_family.isin(ids_tr).to_numpy(),data.episode_family.isin(ids_te).to_numpy()


def _evaluation(model,frame:pd.DataFrame,name:str,target:str):
    y=frame[target].astype(int).to_numpy()
    if not len(y):return {'cohort':name,'rows':0,'valid_two_class':False}
    x=build_features(frame)
    prob=model.predict_proba(x)[:,list(model.classes_).index(1)]
    pred=(prob>=0.5).astype(int)
    valid=len(set(y))==2
    return {'cohort':name,'rows':int(len(frame)),
        'families':int(frame.episode_family.nunique()),'positive_rows':int(y.sum()),
        'valid_two_class':bool(valid),'confusion_matrix':confusion_matrix(y,pred,labels=[0,1]).tolist(),
        'precision':float(precision_score(y,pred,zero_division=0)),
        'recall':float(recall_score(y,pred,zero_division=0)),
        'pr_auc':float(average_precision_score(y,prob)) if valid else None,
        'roc_auc':float(roc_auc_score(y,prob)) if valid else None}


def train(path:Path,out:Path,seed:int=20261012,policy:str='secure_milp'):
    out.mkdir(parents=True,exist_ok=True)
    all_data=pd.read_csv(path)
    if policy not in ('secure_milp','priority_milp'):
        raise ValueError('Only single-step policies, NOT MPC/RL')
    data=all_data.loc[all_data.policy.eq(policy)].copy()
    if data.empty:raise ValueError('No rows for requested policy')
    # Exclude stress cohort, whose sampling deliberately exaggerates risk.
    main=data.loc[~data.sampling_cohort.eq('stress_ood')].copy()
    holdout=data.loc[data.sampling_cohort.eq('stress_ood')].copy()
    # Separate cohort: balanced-risk metrics must have both labels on both sides.
    target='future_P0_failure_H'
    good=main.loc[main.future_horizon_valid.astype(str).str.lower().isin(['true','1'])].copy()
    ood=holdout.loc[holdout.future_horizon_valid.astype(str).str.lower().isin(['true','1'])].copy()
    if len(good)==0:raise ValueError('No full-horizon samples')
    tr,te=_groups_split(good,target,seed)
    y_train=good.loc[tr,target].astype(int)
    metadata_path=path.parent/'dataset_metadata.json'
    label_steps=int(json.loads(metadata_path.read_text()).get('future_label_steps',4)) if metadata_path.exists() else None
    result={'model_family':'random_forest','policy':policy,'target':target,
        'label_semantics':f'next {label_steps} intervals after pre-action t, conditional on observed policy; not fault probability',
        'main_families':int(main.episode_family.nunique()),'stress_ood_families':int(holdout.episode_family.nunique()),
        'main_positive_families':int(good.groupby('episode_family')[target].max().sum()),
        'train_families':int(good.loc[tr].episode_family.nunique()),
        'test_families':int(good.loc[te].episode_family.nunique()),
        'feature_columns':FEATURES,
        'validity_constraints':['synthetic surrogate labels only','OOD stress is reserved','no physical safety certificate']}
    risk_dir=out/'risk';risk_dir.mkdir(exist_ok=True)
    if y_train.nunique()<2:
        result['risk_status']='SKIPPED_NO_BOTH_CLASSES_IN_TRAIN'
        result['risk_warning']='Generate additional independent boundary cases. Do not report binary accuracy.'
    else:
        model=RandomForestClassifier(n_estimators=180,min_samples_leaf=2,class_weight='balanced_subsample',
                                     random_state=seed,n_jobs=-1)
        model.fit(build_features(good.loc[tr]),y_train)
        dump({'model':model,'features':FEATURES,'target':target},risk_dir/'risk_rf.joblib')
        scores=[_evaluation(model,good.loc[te],'heldout_main',target),
                _evaluation(model,ood,'stress_ood',target)]
        result['risk_status']='TRAINED'
        result['risk_evaluations']=scores
        test=good.loc[te,['episode_family','step',target]].copy()
        test['predicted_probability']=model.predict_proba(build_features(good.loc[te]))[:,list(model.classes_).index(1)]
        test.to_csv(risk_dir/'heldout_predictions.csv',index=False)
    # Behavior-clone executed (feasible) security MILP outputs, never proposals.
    actions=main.dropna(subset=ACTIONS).copy()
    train_mask,test_mask=_groups_split(actions,'p0_failed',seed)
    reg=RandomForestRegressor(n_estimators=100,min_samples_leaf=2,random_state=seed,n_jobs=-1)
    reg.fit(build_features(actions.loc[train_mask]),actions.loc[train_mask,ACTIONS])
    preds=reg.predict(build_features(actions.loc[test_mask]))
    result['imitation']={'train_families':int(actions.loc[train_mask].episode_family.nunique()),
         'test_families':int(actions.loc[test_mask].episode_family.nunique()),
         'heldout_MAE_native_units':{name:float(mean_absolute_error(actions.loc[test_mask,name],preds[:,i]))
                                      for i,name in enumerate(ACTIONS)},
         'safety':'Model actions NEVER directly actuated; must pass real MILP with capacity/ENS constraints'}
    imitation_dir=out/'imitation';imitation_dir.mkdir(exist_ok=True)
    dump({'model':reg,'features':FEATURES,'outputs':ACTIONS},imitation_dir/'imitation_rf.joblib')
    (out/'combined_metrics.json').write_text(json.dumps(result,indent=2,ensure_ascii=False),encoding='utf-8')
    return result

if __name__=='__main__':
    p=argparse.ArgumentParser()
    p.add_argument('--data',type=Path,default=Path('outputs/v42_training_preview/closed_loop_expert_steps.csv'))
    p.add_argument('--output-dir',type=Path,default=Path('outputs/v42_baselines'))
    p.add_argument('--policy',choices=['secure_milp','priority_milp'],default='secure_milp')
    p.add_argument('--seed',type=int,default=20261012)
    a=p.parse_args()
    print(json.dumps(train(a.data,a.output_dir,a.seed,a.policy),indent=2,ensure_ascii=False))
